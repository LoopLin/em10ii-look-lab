# -*- coding: utf-8 -*-
"""build_beta_stash.py —— B24f「stash 探针」：不再猜结构体偏移。

思路（见 docs/firmware/beta/B24c-modeprobe.md §7）：
  1. 派发器 0x604B8098 在 0x604B811D 把判别量算成 32 位 key 放进 d2；
     我们把 0x604B8129 的 5 字节换成远跳，进 stub SD：
        k = ((key>>24)&3)<<3 | (key&7)
        把 k 写进 stash（0x605DEDC0，tone 池 slot 53 内的空闲字节）
        然后回到 0x604B812F（bcc，标志位保持）
  2. 上传器 0x60479A27 的 5 字节换成远跳，进 stub SU：
        读 stash 的 k，a2 = 0x605D8344 + k*0x200，跳回原厂拷贝循环 0x60479A3A

这样"谁选表"这件事完全不依赖 ctx 里模式字段的偏移——key 是派发器自己算出来的。

用法：python tools/build_beta_stash.py [--out build/B24f_stash.BIN]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import oly_container as oc  # noqa: E402
from build_beta_modeprobe import (BASE, TONE, SLOT, N_TABLES, STOCK,  # noqa: E402
                                  STOCK_DECODED, MATRIX_RAM, INSERT_RAM,
                                  probe_table, evenize_matrix)

SD_RAM = 0x605DED44        # stub SD（派发器侧）
SU_RAM = 0x605DED80        # stub SU（上传器侧）
STASH_RAM = 0x605DEDC0     # 存 k 的一字节
SD_INSERT = 0x604B8129     # 原 cmp 0x2000096,d2 的前 5 字节
AUDIT = ROOT / 'tools' / 'audit_beta_pack.py'


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build(out: Path, sd_name: str = 'b24f_sd.bin', sd_insert: int = SD_INSERT,
          sd_patch_disp: bool = False, su_name: str = 'b24f_su.bin') -> int:
    sd = (ROOT / '.tmp' / sd_name).read_bytes()
    su = (ROOT / '.tmp' / su_name).read_bytes()
    if sd_patch_disp:
        # 最后 5 字节是占位的 DC jmp，把它改成跳回 sd_insert 之后
        sd = bytearray(sd)
        off = len(sd) - 5
        disp = (sd_insert + 7) - (SD_RAM + off)
        sd[off + 1:off + 5] = (disp & 0xFFFFFFFF).to_bytes(4, 'little')
        sd = bytes(sd)
    for name, blob in (('sd', sd), ('su', su)):
        if not (8 <= len(blob) <= 0x80):
            raise SystemExit(f'stub {name} is {len(blob)} B')

    patches: list[tuple[int, bytes, str]] = []
    for k in range(N_TABLES):
        patches.append((TONE + k * SLOT, probe_table(k), f'tone{k}'))
    patches.append((SD_RAM, sd, 'stub_sd'))
    patches.append((SU_RAM, su, 'stub_su'))
    patches.append((STASH_RAM, b'\xff', 'stash_init_FF'))
    patches.append((sd_insert, b'\xdc' + ((SD_RAM - sd_insert) & 0xFFFFFFFF).to_bytes(4, 'little'), 'jmp_sd'))
    patches.append((INSERT_RAM, b'\xdc' + ((SU_RAM - INSERT_RAM) & 0xFFFFFFFF).to_bytes(4, 'little'), 'jmp_su'))

    stock_img = STOCK_DECODED.read_bytes()
    m_old = list(struct.unpack_from('<9h', stock_img, MATRIX_RAM - BASE))
    m_new = evenize_matrix(m_old)
    if m_new != m_old:
        patches.append((MATRIX_RAM, struct.pack('<9h', *m_new), 'matrix'))

    pf = ROOT / '.tmp' / 'B24f_stash.patch'
    lines = ['# B24f stash probe: 32 band tables + dispatch stash + uploader swap',
             '# generated by tools/build_beta_stash.py']
    for ram, data, _ in patches:
        lines.append(f'ram 0x{ram:08X}={data.hex()}')
    pf.write_text('\n'.join(lines) + '\n', encoding='utf-8')

    out.parent.mkdir(exist_ok=True)
    if out.exists():
        out.unlink()
    cmd = [sys.executable, str(ROOT / 'tools' / 'mkpatch.py'), str(STOCK),
           '--out', str(out), '--patch-file', str(pf)]
    subprocess.run(cmd, check=True, cwd=ROOT)

    blob = out.read_bytes()
    decoded = oc.parse(blob)[0].payload
    (ROOT / '.tmp' / 'B24f.decoded.bin').write_bytes(decoded)

    errs = []
    for ram, data, tag in patches:
        got = decoded[ram - BASE:ram - BASE + len(data)]
        if got != data:
            errs.append(f'{tag} mismatch at 0x{ram:08X}')
    # 区外 0 字节
    stock = STOCK_DECODED.read_bytes()
    outside = 0
    for i, (a, b) in enumerate(zip(stock, decoded)):
        if a != b:
            ram = BASE + i
            if not any(r <= ram < r + len(d) for r, d, _ in patches):
                outside += 1
    if outside:
        errs.append(f'{outside} bytes changed outside intended ranges')

    meta = {'out': out.name, 'sha256': sha256(blob), 'size': len(blob),
            'stub_sd': {'ram': hex(SD_RAM), 'len': len(sd), 'hex': sd.hex()},
            'stub_su': {'ram': hex(SU_RAM), 'len': len(su), 'hex': su.hex()},
            'stash': hex(STASH_RAM), 'insert_sd': hex(sd_insert),
            'insert_su': hex(INSERT_RAM), 'errors': errs}
    (ROOT / '.tmp' / 'B24f_stash.meta.json').write_text(
        json.dumps(meta, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f"OUT   {out}  sha256={meta['sha256'][:16]}  errs={errs or 'none'}")
    rc = subprocess.run([sys.executable, str(AUDIT), str(out)], cwd=ROOT).returncode
    return rc or (1 if errs else 0)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='build/B24f_stash.BIN')
    ap.add_argument('--sd', default='b24f_sd.bin')
    ap.add_argument('--sd-insert', default=hex(SD_INSERT))
    ap.add_argument('--su', default='b24f_su.bin')
    args = ap.parse_args()
    return build((ROOT / args.out).resolve(), args.sd, int(args.sd_insert, 0), args.sd != 'b24f_sd.bin', args.su)


if __name__ == '__main__':
    raise SystemExit(main())
