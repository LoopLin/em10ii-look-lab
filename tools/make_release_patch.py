#!/usr/bin/env python3
"""Generate a single patch file (blk N:OFF=HEX lines) from two images.

Usage: python tools/make_release_patch.py <base.BIN> <target.BIN> <out.patch>
Offsets emitted are *decoded payload* offsets, accepted by mkpatch.py as
``blk N:0xOFF=HEX``.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import oly_container as oc  # noqa: E402

GAP = 16          # merge runs closer than this
MAXLINE = 64      # max bytes per emitted line


def runs(a: bytes, b: bytes) -> list[tuple[int, int]]:
    out, start, last = [], None, None
    for i, (x, y) in enumerate(zip(a, b)):
        if x != y:
            if start is None:
                start = i
            elif i - last > GAP:
                out.append((start, last + 1))
                start = i
            last = i
    if start is not None:
        out.append((start, last + 1))
    return out


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print(__doc__)
        return 2
    base_p, tgt_p, out_p = (Path(x) for x in argv[1:])
    base = oc.parse(base_p.read_bytes())
    tgt = oc.parse(tgt_p.read_bytes())
    if len(base) != len(tgt):
        print(f"block count differs: {len(base)} vs {len(tgt)}")
        return 1
    lines = ["# generated by tools/make_release_patch.py",
             f"# base   {base_p.name}",
             f"# target {tgt_p.name}"]
    total = 0
    for n, (bb, tb) in enumerate(zip(base, tgt)):
        bp, tp = bb.payload, tb.payload
        if len(bp) != len(tp):
            print(f"block {n} size differs")
            return 1
        for s, e in runs(bp, tp):
            cur = s
            while cur < e:
                chunk = tp[cur:min(cur + MAXLINE, e)]
                lines.append(f"blk {n}:0x{cur:x}={chunk.hex()}")
                total += len(chunk)
                cur += len(chunk)
    out_p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{out_p}: {len(lines)-3} lines, {total} bytes changed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
