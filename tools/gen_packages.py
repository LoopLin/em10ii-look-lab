def main():
    log = open('docs/firmware/FLASH-LOG.md', encoding='utf-8').read().splitlines()
    body = []
    n = 0
    for line in log:
        if not (line.startswith('|') and 'BIN' in line):
            continue
        c = [x.strip() for x in line.strip('|').split('|')]
        if len(c) < 4:
            continue
        n += 1
        t, pkg, sha, note = c[0], c[1], c[2], c[3]
        if '真机' in note:
            res = '成（真机）'
        elif '模拟' in note:
            res = '未测'
        else:
            res = note[:24]
        body.append('| %d | %s | %s | %s | %s |' % (n, pkg, sha[:16], t, res))
    open('docs/firmware/PACKAGES.md', 'w', encoding='utf-8').write(HEAD + '\n'.join(body) + TAIL)
    print('rows', n)

if __name__ == '__main__':
    main()
